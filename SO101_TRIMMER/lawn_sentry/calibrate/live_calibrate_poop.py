import cv2
import poop_config as cfg

from trimmer_arm import TrimmerArm
from trim_detector import build_pipeline
from camera_session import CameraSession

STEP = 20

def save_pose(arm):

    pose = {
        cfg.SHOULDER_ID: arm.read_position(cfg.SHOULDER_ID),
        cfg.ELBOW_ID: arm.read_position(cfg.ELBOW_ID),
        cfg.WRIST_ID: arm.read_position(cfg.WRIST_ID),
    }

    with open("poop_scan_pose.py", "w") as f:
        f.write(
            '"""Generated by live_calibrate_poop.py"""\n'
        )
        f.write(f"SCAN_POSE = {pose!r}\n")

    print("saved:", pose)

def main():

    arm = TrimmerArm()

    arm.enable()

    cam = CameraSession(build_pipeline)

    print("W/S shoulder")
    print("E/D elbow")
    print("R/F wrist")
    print("A/Z base")
    print("P save")
    print("Q quit")

    while True:

        g = cam.get()

        if g is not None:

            img = g["rgb"].getCvFrame()

            cv2.putText(
                img,
                "P=save pose  Q=quit",
                (10,30),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.7,
                (0,255,255),
                2
            )

            cv2.imshow("Poop Calibration", img)

        k = cv2.waitKey(1) & 255

        if k == ord("q"):
            break

        if k == ord("p"):
            save_pose(arm)

        if k == ord("w"):
            arm.move_to(
                cfg.SHOULDER_ID,
                arm.read_position(cfg.SHOULDER_ID) - STEP
            )

        if k == ord("s"):
            arm.move_to(
                cfg.SHOULDER_ID,
                arm.read_position(cfg.SHOULDER_ID) + STEP
            )

        if k == ord("e"):
            arm.move_to(
                cfg.ELBOW_ID,
                arm.read_position(cfg.ELBOW_ID) - STEP
            )

        if k == ord("d"):
            arm.move_to(
                cfg.ELBOW_ID,
                arm.read_position(cfg.ELBOW_ID) + STEP
            )

        if k == ord("r"):
            arm.move_to(
                cfg.WRIST_ID,
                arm.read_position(cfg.WRIST_ID) - STEP
            )

        if k == ord("f"):
            arm.move_to(
                cfg.WRIST_ID,
                arm.read_position(cfg.WRIST_ID) + STEP
            )

        if k == ord("a"):
            arm.move_to(
                cfg.BASE_ID,
                arm.read_position(cfg.BASE_ID) - STEP
            )

        if k == ord("z"):
            arm.move_to(
                cfg.BASE_ID,
                arm.read_position(cfg.BASE_ID) + STEP
            )

    arm.close()
    cam.stop()

if __name__ == "__main__":
    main()
